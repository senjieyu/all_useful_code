#!/usr/bin/env python3
# -*- coding: utf-8 -*-

import math
import shutil
import subprocess
from pathlib import Path
import sys


def run(cmd):
    cmd = [str(x) for x in cmd]
    print(">>", " ".join(cmd))
    subprocess.run(cmd, check=True)


def estimate_atoms_fcc(lx, ly, lz, a0):
    # FCC conventional cell: 4 atoms / a0^3
    return 4.0 * lx * ly * lz / (a0 ** 3)


def main():
    # -----------------------------
    # 1) Atomsk path
    # -----------------------------
    atomsk = shutil.which("atomsk")
    if atomsk is None:
        # 改成你自己的 Atomsk 路径
        atomsk = r"D:\2025.916aftersoftware\atmosk\Atomsk\atomsk.EXE"

    if not Path(atomsk).exists():
        print("Error: Atomsk not found.")
        print("Please check the path in the script.")
        sys.exit(1)

    # -----------------------------
    # 2) Working directory
    # -----------------------------
    workdir = Path("atomsk_hex_poly_test").resolve()
    workdir.mkdir(exist_ok=True)

    # -----------------------------
    # 3) Basic parameters
    # -----------------------------
    a0 = 3.615  # Cu lattice constant, Angstrom

    # 盒子尺寸
    # 这里做成比较适合蜂窝平铺的尺寸
    # 大小大约是几千原子量级，适合先看结构
    Lx = 80.0
    d = 20.0
    dx = d
    dy = math.sqrt(3.0) * 0.5 * d
    Ly = 4 * dy
    Lz = 18.0

    # 取向循环
    angle_pool = [0, 30, 60, 90]

    est_n = estimate_atoms_fcc(Lx, Ly, Lz, a0)
    print(f"Estimated atom count before GB deletion/wrapping: {est_n:.0f}")

    # -----------------------------
    # 4) File names
    # -----------------------------
    seed_file = workdir / "seed.xsf"
    poly_file = workdir / "poly_hex.txt"
    poly_cfg = workdir / "hex_poly.cfg"
    wrapped_cfg = workdir / "hex_poly_wrapped.cfg"

    # Atomsk 转 lammps 时通常自动生成同名 .lmp
    # 这里不强依赖名字，最后打印目录内容即可

    # -----------------------------
    # 5) Create seed crystal
    # -----------------------------
    # 用正交晶向，先保证能稳定生成
    run([
        atomsk,
        "--create", "fcc", a0, "Cu",
        "orient", "[100]", "[010]", "[001]",
        seed_file
    ])

    # -----------------------------
    # 6) Generate hex-like Voronoi nodes
    # -----------------------------
    # 三角晶格 seed -> Voronoi 后接近六边形蜂窝晶粒
    nodes = []
    row = 0
    y = 0.5 * dy

    while y < Ly - 1e-8:
        x_offset = 0.5 * dx if (row % 2 == 1) else 0.0
        col = 0
        x = 0.5 * dx + x_offset

        while x < Lx - 1e-8:
            angle = angle_pool[(row + col) % len(angle_pool)]
            nodes.append((x, y, 0.5 * Lz, angle))
            x += dx
            col += 1

        y += dy
        row += 1

    # -----------------------------
    # 7) Write polycrystal parameter file
    # -----------------------------
    lines = []
    lines.append(f"box {Lx:.6f} {Ly:.6f} {Lz:.6f}")
    lines.append("")

    for x, y, z, ang in nodes:
        # 围绕 z 轴旋转 ang 度
        lines.append(f"node {x:.6f} {y:.6f} {z:.6f}   0   0   {ang}")

    lines.append("")
    poly_file.write_text("\n".join(lines), encoding="utf-8")

    print(f"Wrote polycrystal parameter file: {poly_file}")
    print(f"Number of nodes: {len(nodes)}")

    # -----------------------------
    # 8) Build polycrystal
    # -----------------------------
    run([
        atomsk,
        "--polycrystal",
        seed_file,
        poly_file,
        poly_cfg
    ])

    # -----------------------------
    # 9) Wrap atoms back into the cell
    # -----------------------------
    run([
        atomsk,
        poly_cfg,
        "-wrap",
        wrapped_cfg
    ])

    # -----------------------------
    # 10) Export to LAMMPS data
    # -----------------------------
    run([
        atomsk,
        wrapped_cfg,
        "lammps"
    ])

    # -----------------------------
    # 11) Print summary
    # -----------------------------
    print("\nDone.")
    print("Generated files:")
    for p in sorted(workdir.iterdir()):
        print(" -", p.name)

    print("\nRecommended LAMMPS header:")
    print("units metal")
    print("atom_style atomic")
    print("boundary p p p")
    print("read_data hex_poly_wrapped.lmp   # or the .lmp file generated by Atomsk")


if __name__ == "__main__":
    main()
