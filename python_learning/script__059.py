# 类的命名用驼峰体
#类是对象相似数据与功能的集合体
#所以类中最常见的变量与函数的定义，但是类体其实是可以包含任意其他代码的
#注意：类体代码是在类定义阶段就会立即执行,会产生名称空间

class Student:
    # 变量的定义(共有的数据 )
    school='清华大学'
    # 功能的定义
    #该方法会在对象产生之后自动执行，专门为对象进行初始化操作，可以有任意代码，但一定不能返回非None的值
    #类的调用阶段执行   调用类的时候执行init方法
    def __init__(self,name,sex,age):
        self.name=name
        self.sex=sex
        self.age=age

    def choose(self):
        print('%s is choosing a course' %self.name)


    # print('asdadasdasdas========asdadasdasda')


