#调用类的过程称为实例化,发生了三件事
# 1.先产生一个空对象
# 2.python会自动调用类中的__init__方法，
# 然后将空对象以及调用类是括号内传入的参数一同传给__init__
# 3.返回初始化完的对象
stu_1 = Student('asd','male',15)
stu_1.choose()
stu_2 = Student('asd','male',16)
print(stu_1.__dict__)#{'name': 'asd', 'sex': 'male', 'age': 15}

#对象自己名称空间中没有的属性到类中去找
